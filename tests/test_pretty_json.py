class TestPrettyJSONFormatting(unittest.TestCase):
    """Test suite ensuring all generated/persisted JSON files are formatted with 2-space indentation."""

    def setUp(self) -> None:
        self.temp_dir = tempfile.TemporaryDirectory()
        self.workspace = Path(self.temp_dir.name).resolve()

        # Initialize mock git repository under repos/core on a compliant branch
        self.repo_dir = self.workspace / "repos" / "core"
        self.repo_dir.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "init", "-b", "feature/pretty"], cwd=str(self.repo_dir), check=True, capture_output=True)
        subprocess.run(["git", "config", "user.name", "Tester"], cwd=str(self.repo_dir), check=True, capture_output=True)
        subprocess.run(["git", "config", "user.email", "test@stagecheck.local"], cwd=str(self.repo_dir), check=True, capture_output=True)
        readme = self.repo_dir / "service.py"
        readme.write_text("def run(): return 42\n", encoding="utf-8")
        subprocess.run(["git", "add", "service.py"], cwd=str(self.repo_dir), check=True, capture_output=True)
        subprocess.run(["git", "commit", "-m", "Initial commit"], cwd=str(self.repo_dir), check=True, capture_output=True)

        res = subprocess.run(["git", "rev-parse", "HEAD"], cwd=str(self.repo_dir), capture_output=True, text=True, check=True)
        self.head_sha = res.stdout.strip()

    def tearDown(self) -> None:
        try:
            elevate_permissions_for_teardown(self.workspace)
        except Exception:
            pass
        self.temp_dir.cleanup()

    def assert_pretty_json_file(self, file_path: Path) -> None:
        """Assert that a file exists and is formatted as human-readable 2-space indented multi-line JSON."""
        self.assertTrue(file_path.is_file(), f"File does not exist: {file_path}")
        text = file_path.read_text(encoding="utf-8")

        # 1. Output must end with a newline
        self.assertTrue(text.endswith("\n"), f"{file_path} must end with a newline")

        # 2. Multi-line formatting (must not be minified into 1 line)
        lines = text.splitlines()
        self.assertGreater(len(lines), 1, f"{file_path} must be multi-line (got {len(lines)} lines)")

        # 3. Must be valid JSON
        data = json.loads(text)

        # 4. Must match pretty_json_dumps output
        expected = pretty_json_dumps(data)
        self.assertEqual(text, expected, f"{file_path} content did not match expected pretty-printed formatting")

    def test_example_from_specification(self) -> None:
        """Verify the exact before/after example from the specification."""
        raw_data = {
            "agent": "agent1",
            "status": "ready",
            "config": {"enabled": True, "mode": "strict"},
            "checks": ["security", "quality", "compliance"],
        }
        output = pretty_json_dumps(raw_data)
        expected = (
            "{\n"
            '  "agent": "agent1",\n'
            '  "status": "ready",\n'
            '  "config": {\n'
            '    "enabled": true,\n'
            '    "mode": "strict"\n'
            "  },\n"
            '  "checks": [\n'
            '    "security",\n'
            '    "quality",\n'
            '    "compliance"\n'
            "  ]\n"
            "}\n"
        )
        self.assertEqual(output, expected)

    def test_init_scaffolded_json_files_are_pretty_printed(self) -> None:
        """Verify all control descriptors and specs generated by stagecheck init are pretty-printed."""
        ret = run_init(
            workspace=str(self.workspace),
            repos="core",
            force=False,
            agent1="claude",
            agent2="codex",
        )
        self.assertEqual(ret, 0)

        # Elevate permissions to read files cleanly
        elevate_permissions_for_teardown(self.workspace)

        control_files = [
            self.workspace / "controls" / "STAGECHECK_ROOT.json",
            self.workspace / "controls" / "EVIDENCE_ROOT.json",
            self.workspace / "controls" / "PRODUCT_REPOSITORIES.json",
            self.workspace / "controls" / "QUALIFICATION_ROOT.json",
            self.workspace / "controls" / "ACTIVE_STATE.json",
            self.workspace / "controls" / "DISPOSITIONS.json",
            self.workspace / "specs" / "TASK_PLAN.json",
        ]

        for cf in control_files:
            with self.subTest(file=cf.name):
                self.assert_pretty_json_file(cf)

    def test_state_transitions_preserve_pretty_formatting(self) -> None:
        """Verify save_active_state maintains multi-line formatting."""
        run_init(workspace=str(self.workspace), repos="core", agent1="claude", agent2="codex")
        elevate_permissions_for_teardown(self.workspace)

        state = load_active_state(self.workspace)
        state["phase"] = "PHASE_1_PLANNING"
        state["task_id"] = "task-pretty"
        save_active_state(self.workspace, state)

        elevate_permissions_for_teardown(self.workspace)
        state_file = self.workspace / "controls" / "ACTIVE_STATE.json"
        self.assert_pretty_json_file(state_file)

    def test_circuit_breaker_transitions_preserve_pretty_formatting(self) -> None:
        """Verify circuit breaker trip and unlatch write pretty-printed ACTIVE_STATE.json."""
        run_init(workspace=str(self.workspace), repos="core", agent1="claude", agent2="codex")
        elevate_permissions_for_teardown(self.workspace)

        eval_tripped = CircuitBreakerEvaluation(
            tripped=True,
            trigger="stagnant_defects",
            reason="Zero defect reduction between attempts",
        )
        trip_circuit_breaker(self.workspace, "task-cb", 2, eval_tripped, [])

        elevate_permissions_for_teardown(self.workspace)
        state_file = self.workspace / "controls" / "ACTIVE_STATE.json"
        self.assert_pretty_json_file(state_file)

        reset_circuit_breaker(self.workspace, "task-cb", "human-operator")
        elevate_permissions_for_teardown(self.workspace)
        self.assert_pretty_json_file(state_file)

    def test_dispositions_and_resume_preserve_pretty_formatting(self) -> None:
        """Verify adding dispositions and resume write pretty-printed JSON files."""
        run_init(workspace=str(self.workspace), repos="core", agent1="claude", agent2="codex")
        elevate_permissions_for_teardown(self.workspace)

        evidence_file = self.workspace / "evidence" / "waiver_proof.txt"
        evidence_file.parent.mkdir(parents=True, exist_ok=True)
        evidence_file.write_text("Waiver proof data\n", encoding="utf-8")

        add_disposition(
            workspace_root=self.workspace,
            task_id="task-init",
            defect_id="sec.gitleaks",
            rationale="Test waiver",
            authorized_by="owner@stagecheck.local",
            evidence_path="evidence/waiver_proof.txt",
            confirmed=True,
        )
