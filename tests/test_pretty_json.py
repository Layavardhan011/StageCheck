    def test_orchestrator_verdict_is_pretty_printed(self) -> None:
        """Verify 9-stage audit verdict.json is pretty-printed."""
        run_init(workspace=str(self.workspace), repos="core", agent1="claude", agent2="codex")
        elevate_permissions_for_teardown(self.workspace)

        # Create necessary inputs for audit
        p1_dir = self.workspace / "evidence" / "tasks" / "task-orch" / "attempt_1" / "Phase-1"
        p1_dir.mkdir(parents=True, exist_ok=True)
        (p1_dir / "prompt.md").write_text("# Test prompt\n", encoding="utf-8")
        scope = {"schema_version": "2.0", "task_id": "task-orch", "allowed_paths": ["repos/core/**"]}
        (p1_dir / "declared_scope.json").write_text(pretty_json_dumps(scope), encoding="utf-8")
        freeze_prompt_and_scope(self.workspace, "task-orch", 1, ["core"])

        p2a_dir = self.workspace / "evidence" / "tasks" / "task-orch" / "attempt_1" / "Phase-2A"
        p2a_dir.mkdir(parents=True, exist_ok=True)
        status_data = {
            "schema_version": "2.0",
            "task_id": "task-orch",
            "attempt": 1,
            "cycle": 1,
            "status": "APPROVED",
            "touched_repositories": ["core"],
            "base_commits": {"core": self.head_sha},
            "summary": "Ready",
        }
        (p2a_dir / "pre_commit_status.json").write_text(pretty_json_dumps(status_data), encoding="utf-8")
        record_pre_commit_review(
            workspace_root=self.workspace,
            task_id="task-orch",
            attempt=1,
            cycle=1,
            status="APPROVED",
            summary="Approved",
            base_commits={"core": self.head_sha},
        )

        run_audit(
            workspace_root=self.workspace,
            task_id="task-orch",
            attempt=1,
        )

        elevate_permissions_for_teardown(self.workspace)
        verdict_file = self.workspace / "evidence" / "tasks" / "task-orch" / "attempt_1" / "Phase-3" / "verdict.json"
        self.assert_pretty_json_file(verdict_file)
        task_root_verdict = self.workspace / "evidence" / "tasks" / "task-orch" / "verdict.json"
        self.assert_pretty_json_file(task_root_verdict)


