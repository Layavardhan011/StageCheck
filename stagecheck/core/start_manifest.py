"""Specification Baseline Manifest Protocol and Integrity Verifier (FR-08 / Spec 05 / DEC-008).

Implements generation, parsing, verification, and authorized updates for specs/START_MANIFEST.md.
Ensures deterministic SHA-256 digests, tamper detection, unregistered file detection,
and eliminates manifest self-hash cycles.
"""

from __future__ import annotations

import datetime
import os
import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union

from stagecheck.core.paths import safe_resolve
from stagecheck.core.utils import sha256_file


class SpecManifestError(Exception):
    """Base exception for specification manifest errors."""


class SpecManifestNotFoundError(SpecManifestError):
    """Raised when specs/START_MANIFEST.md is not found."""


class SpecManifestSecurityError(SpecManifestError):
    """Raised when symbolic links or unsafe path traversals are detected in specs/."""


class SpecManifestVerificationError(SpecManifestError):
    """Raised when specification files fail integrity verification."""

    def __init__(self, message: str, details: Optional[Dict[str, Any]] = None):
        super().__init__(message)
        self.details = details or {}


START_MANIFEST_FILENAME = "START_MANIFEST.md"


def get_spec_manifest_path(workspace_root: Union[str, Path]) -> Path:
    """Return the absolute path to specs/START_MANIFEST.md."""
    root = Path(workspace_root).resolve()
    return root / "specs" / START_MANIFEST_FILENAME


def _check_specs_symlinks(specs_dir: Path) -> None:
    """Inspect specs directory and reject any symbolic links (Pre-Resolution Symlink Check)."""
    if specs_dir.is_symlink():
        raise SpecManifestSecurityError(f"specs directory '{specs_dir}' is a symbolic link.")

    for entry in specs_dir.rglob("*"):
        if entry.is_symlink():
            raise SpecManifestSecurityError(
                f"Symbolic link detected in specs directory: '{entry}' is prohibited."
            )


def generate_start_manifest(
    workspace_root: Union[str, Path],
    project_name: str = "stagecheck-workspace",
    timestamp: Optional[str] = None,
) -> Path:
    """Generate specs/START_MANIFEST.md with baseline SHA-256 digests of all specs/ files.

    Strictly excludes START_MANIFEST.md to prevent self-hash cycles.
    Rejects any symbolic links before hashing.
    """
    root = Path(workspace_root).resolve()
    specs_dir = root / "specs"
    specs_dir.mkdir(parents=True, exist_ok=True)

    _check_specs_symlinks(specs_dir)

    manifest_file = specs_dir / START_MANIFEST_FILENAME
    ts = timestamp or datetime.datetime.now(datetime.timezone.utc).isoformat()

    # Collect all regular files in specs/ recursively excluding root START_MANIFEST.md
    spec_files: List[Tuple[str, str, str, str]] = []
    for f in sorted(specs_dir.rglob("*")):
        if f.is_dir():
            continue
        if f.is_symlink():
            raise SpecManifestSecurityError(
                f"Symbolic link prohibited in specifications directory: '{f}'."
            )
        rel_sub = f.relative_to(specs_dir).as_posix()
        if rel_sub == START_MANIFEST_FILENAME:
            continue
        rel_path = f"specs/{rel_sub}"
        f_hash = sha256_file(f)
        status = "Authoritative Roadmap" if rel_sub == "TASK_PLAN.json" else (
            "System Architecture" if rel_sub == "ARCHITECTURE.md" else "Specification Deliverable"
        )
        spec_files.append((rel_sub, rel_path, f_hash, status))

    manifest_lines = [
        "# Project Specification Baseline Manifest (`START_MANIFEST.md`)\n\n",
        "**Generated by:** StageCheck Scaffolding Engine (v2.0.0)  \n",
        f"**Timestamp:** {ts}  \n",
        f"**Project Name:** {project_name}  \n\n",
        "This manifest records the authoritative SHA-256 digests of all project specification files located in `specs/` at workspace initialization.\n\n",
        "| Specification File | Relative Path | SHA-256 Digest | Status |\n",
        "|---|---|---|---|\n",
    ]

    for fname, rpath, fhash, status in spec_files:
        manifest_lines.append(f"| `{fname}` | `{rpath}` | `{fhash}` | {status} |\n")

    manifest_lines.extend([
        "\n---\n\n",
        "## Integrity Invariant\n",
        "- Any subsequent addition of a specification file to `specs/` must be registered in this table.\n",
        "- In Phase 3 Preflight Verification (Stage 1), StageCheck asserts that every file in `specs/` matches its digest in `START_MANIFEST.md`.\n",
    ])

    manifest_content = "".join(manifest_lines)
    manifest_file.write_text(manifest_content, encoding="utf-8")
    return manifest_file


def parse_start_manifest(workspace_root: Union[str, Path]) -> Dict[str, str]:
    """Parse specs/START_MANIFEST.md and return a dictionary of {filename_or_relpath: sha256_digest}."""
    manifest_file = get_spec_manifest_path(workspace_root)
    if not manifest_file.is_file():
        raise SpecManifestNotFoundError(f"Manifest file not found: '{manifest_file}'")

    if manifest_file.is_symlink():
        raise SpecManifestSecurityError(f"START_MANIFEST.md is a symlink: '{manifest_file}'")

    text = manifest_file.read_text(encoding="utf-8")
    entries: Dict[str, str] = {}

    # Parse Markdown table rows: | `file` | `specs/file` | `hash` | ... |
    # Matches rows with 3 or 4 columns
    row_pattern = re.compile(
        r"\|\s*`?([a-zA-Z0-9._\-/]+)`?\s*\|\s*`?([a-zA-Z0-9._\-/]+)`?\s*\|\s*`?([0-9a-fA-F]{64})`?\s*\|"
    )

    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("|") or "---" in line or "Relative Path" in line:
            continue
        match = row_pattern.search(line)
        if match:
            fname = match.group(1).strip()
            rpath = match.group(2).strip()
            fhash = match.group(3).strip().lower()
            # Store by both filename and relative path for flexible lookup
            entries[fname] = fhash
            entries[rpath] = fhash

    return entries


def verify_spec_manifest(
    workspace_root: Union[str, Path],
    strict: bool = False,
) -> Dict[str, Any]:
    """Verify specification integrity against specs/START_MANIFEST.md.

    Verifies:
    1. specs/START_MANIFEST.md exists and is not a symlink.
    2. All registered files in START_MANIFEST.md exist on disk.
    3. SHA-256 digest of each registered file matches the recorded digest (tamper detection).
    4. No untracked/unregistered files exist in specs/ (addition detection).
    5. START_MANIFEST.md is excluded from checks (no self-hash cycle).
    6. No symbolic links exist in specs/.

    Args:
        workspace_root: Workspace root path.
        strict: If True, raises SpecManifestVerificationError on failure.

    Returns:
        Dict with keys:
          'valid': bool,
          'verified': list of matched filenames,
          'missing': list of missing filenames,
          'tampered': list of dicts with file, expected, actual,
          'unregistered': list of unrecorded filenames in specs/.
    """
    root = Path(workspace_root).resolve()
    specs_dir = root / "specs"

    if not specs_dir.is_dir():
        if strict:
            raise SpecManifestNotFoundError(f"specs directory does not exist at '{specs_dir}'")
        return {
            "valid": False,
            "error": "specs directory missing",
            "verified": [],
            "missing": [],
            "tampered": [],
            "unregistered": [],
        }

    _check_specs_symlinks(specs_dir)

    manifest_file = specs_dir / START_MANIFEST_FILENAME
    if not manifest_file.is_file():
        if strict:
            raise SpecManifestNotFoundError(f"START_MANIFEST.md not found at '{manifest_file}'")
        return {
            "valid": False,
            "error": "START_MANIFEST.md missing",
            "verified": [],
            "missing": [START_MANIFEST_FILENAME],
            "tampered": [],
            "unregistered": [],
        }

    entries = parse_start_manifest(root)
    # Get mapping of relative path under specs/ -> expected sha256
    recorded_filenames: Dict[str, str] = {}
    for k, v in entries.items():
        if k.startswith("specs/"):
            rel_k = k[len("specs/") :]
            if rel_k and rel_k != START_MANIFEST_FILENAME:
                recorded_filenames[rel_k] = v

    verified: List[str] = []
    missing: List[str] = []
    tampered: List[Dict[str, str]] = []
    unregistered: List[str] = []

    # 1. Verify every recorded file exists within specs/ without escaping or symlinks
    specs_resolved = specs_dir.resolve()
    for fname, expected_hash in sorted(recorded_filenames.items()):
        if ".." in Path(fname).parts or Path(fname).is_absolute():
            raise SpecManifestSecurityError(f"Unsafe specification path in manifest: '{fname}'")
        fpath = (specs_dir / fname)
        if not fpath.resolve().is_relative_to(specs_resolved):
            raise SpecManifestSecurityError(f"Escaping specification path in manifest: '{fname}'")
        if fpath.is_symlink():
            raise SpecManifestSecurityError(f"Symbolic link prohibited in specs/: '{fpath}'")
        if not fpath.is_file():
            missing.append(fname)
        else:
            actual_hash = sha256_file(fpath)
            if actual_hash.lower() != expected_hash.lower():
                tampered.append({
                    "file": fname,
                    "expected": expected_hash,
                    "actual": actual_hash,
                })
            else:
                verified.append(fname)

    # 2. Check recursively for unregistered regular files in specs/
    for f in sorted(specs_dir.rglob("*")):
        if f.is_dir():
            continue
        if f.is_symlink():
            raise SpecManifestSecurityError(f"Symbolic link prohibited in specs/: '{f}'")
        rel_sub = f.relative_to(specs_dir).as_posix()
        if rel_sub == START_MANIFEST_FILENAME:
            continue
        if rel_sub not in recorded_filenames:
            unregistered.append(rel_sub)

    is_valid = len(missing) == 0 and len(tampered) == 0 and len(unregistered) == 0

    result = {
        "valid": is_valid,
        "verified": verified,
        "missing": missing,
        "tampered": tampered,
        "unregistered": unregistered,
    }

    if strict and not is_valid:
        msg_parts = []
        if missing:
            msg_parts.append(f"Missing spec files: {missing}")
        if tampered:
            msg_parts.append(f"Tampered spec files: {[t['file'] for t in tampered]}")
        if unregistered:
            msg_parts.append(f"Unregistered spec additions: {unregistered}")
        raise SpecManifestVerificationError(
            f"Specification manifest verification failed: {'; '.join(msg_parts)}",
            details=result,
        )

    return result


def update_spec_manifest(
    workspace_root: Union[str, Path],
    project_name: str = "stagecheck-workspace",
) -> Path:
    """Explicitly update specs/START_MANIFEST.md with current SHA-256 digests.

    Authorized operator operation to recalculate hashes after approved spec changes.
    """
    return generate_start_manifest(workspace_root, project_name=project_name)
